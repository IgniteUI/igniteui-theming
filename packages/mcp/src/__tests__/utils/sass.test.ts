describe("quoteFontFamily", () => {
  it("quotes unquoted single font names", () => {
    expect(quoteFontFamily("Roboto")).toBe("'Roboto'");
  });

  it("leaves already single-quoted fonts unchanged", () => {
    expect(quoteFontFamily("'Roboto'")).toBe("'Roboto'");
  });

  it("leaves already double-quoted fonts unchanged", () => {
    expect(quoteFontFamily('"Roboto"')).toBe('"Roboto"');
  });

  it("wraps font stacks with double quotes when they contain single quotes", () => {
    const input = "'Titillium Web', sans-serif";
    expect(quoteFontFamily(input)).toBe(`"'Titillium Web', sans-serif"`);
  });

  it("wraps font stacks with single quotes when they contain double quotes", () => {
    const input = '"Titillium Web", sans-serif';
    expect(quoteFontFamily(input)).toBe(`'"Titillium Web", sans-serif'`);
  });

  it("leaves Sass variable references unquoted", () => {
    expect(quoteFontFamily("$typeface")).toBe("$typeface");
    expect(quoteFontFamily("$material-typeface")).toBe("$material-typeface");
  });
});

describe("generateUseStatement", () => {
  it("generates Angular import for angular platform", () => {
    const result = generateUseStatement("angular");
    expect(result).toContain('@use "igniteui-angular/theming" as *;');
  });

  it("generates licensed Angular import when licensed is true", () => {
    const result = generateUseStatement("angular", true);
    expect(result).toContain(
      '@use "@infragistics/igniteui-angular/theming" as *;',
    );
  });

  it("generates generic import for webcomponents platform", () => {
    const result = generateUseStatement("webcomponents");
    expect(result).toContain("@use 'igniteui-theming' as *;");
  });

  it("ignores licensed flag for webcomponents (always free)", () => {
    const result = generateUseStatement("webcomponents", true);
    expect(result).toContain("@use 'igniteui-theming' as *;");
  });

  it("generates generic import when platform is undefined", () => {
    const result = generateUseStatement();
    expect(result).toContain("@use 'igniteui-theming' as *;");
  });

  it("prepends inline placement comment", () => {
    const result = generateUseStatement();
    expect(result).toContain("// NOTE: @use rules must be at the top");
    expect(result.indexOf("// NOTE")).toBeLessThan(result.indexOf("@use"));
  });
});

describe("generatePaletteCode", () => {
  it("generates palette code with required parameters", () => {
    const result = generatePaletteCode({
      primary: "#2ab759",
      secondary: "#f7bd32",
      surface: "white",
    });

    expect(result.variableName).toBe("$custom-light-palette");
    expect(result.paletteDefinition.join("\n")).toContain("$primary: #2ab759");
    expect(result.paletteDefinition.join("\n")).toContain(
      "$secondary: #f7bd32",
    );
    expect(result.paletteDefinition.join("\n")).toContain("$surface: white");
  });

  it("uses custom variable name when provided", () => {
    const result = generatePaletteCode({
      primary: "#2ab759",
      secondary: "#f7bd32",
      surface: "white",
      variableName: "my-brand",
    });

    expect(result.variableName).toBe("$my-brand");
  });

  it("uses dark variant in variable name", () => {
    const result = generatePaletteCode({
      primary: "#2ab759",
      secondary: "#f7bd32",
      surface: "#121212",
      variant: "dark",
    });

    expect(result.variableName).toBe("$custom-dark-palette");
  });

  it("includes optional colors when provided", () => {
    const result = generatePaletteCode({
      primary: "#2ab759",
      secondary: "#f7bd32",
      surface: "white",
      gray: "#333",
      info: "#0288d1",
      success: "#4caf50",
      warn: "#ff9800",
      error: "#f44336",
    });

    const code = result.paletteDefinition.join("\n");
    expect(code).toContain("$gray: #333");
    expect(code).toContain("$info: #0288d1");
    expect(code).toContain("$success: #4caf50");
    expect(code).toContain("$warn: #ff9800");
    expect(code).toContain("$error: #f44336");
  });

  it("generates variable references when useVariableReferences is true", () => {
    const result = generatePaletteCode({
      primary: "#2ab759",
      secondary: "#f7bd32",
      surface: "white",
      useVariableReferences: true,
    });

    expect(result.colorVariables).toContain("$primary-color: #2ab759;");
    expect(result.colorVariables).toContain("$secondary-color: #f7bd32;");
    expect(result.colorVariables).toContain("$surface-color: white;");
    expect(result.paletteDefinition.join("\n")).toContain(
      "$primary: $primary-color",
    );
  });
});

describe("generateThemeSass", () => {
  it("uses the preset palette of the design system and variant without custom colors", () => {
    const { code, variables } = generateThemeSass({
      designSystem: "indigo",
      variant: "dark",
      platform: "webcomponents",
    });

    expect(code).toContain(`@use '${THEME_ENTRY_POINT}' as *;`);
    expect(code).toContain(
      "@include typography($font-family: $indigo-typeface, $type-scale: $indigo-type-scale, $allow-exclusion: true);",
    );
    expect(code).toContain(
      "@include theme($palette: $dark-indigo-palette, $schema: $dark-indigo-schema);",
    );
    expect(code).not.toContain("palette(\n");
    expect(variables).toEqual([
      "$dark-indigo-palette",
      "$dark-indigo-schema",
      "$indigo-typeface",
      "$indigo-type-scale",
    ]);
  });

  it("defines a custom palette, with the preset colors for the ones not given", () => {
    const { code, variables } = generateThemeSass({
      designSystem: "material",
      variant: "light",
      primaryColor: "#2ab759",
      paletteName: "brand",
      generator: "legacy",
    });

    const preset = PALETTE_PRESETS["light-material-palette"];

    expect(code).toContain(
      `$brand-palette: palette(\n  $primary: #2ab759,\n  $secondary: ${preset.secondary},\n  $surface: ${preset.surface},\n  $generator: 'legacy'\n);`,
    );
    expect(code).toContain(
      "@include theme($palette: $brand-palette, $schema: $light-material-schema);",
    );
    expect(variables[0]).toBe("$brand-palette");
  });

  it("lets the products' elements opt out of the typography, but not standalone use", () => {
    const product = generateThemeSass({
      designSystem: "fluent",
      variant: "light",
      platform: "blazor",
    });
    const generic = generateThemeSass({
      designSystem: "fluent",
      variant: "light",
      platform: "generic",
    });
    const none = generateThemeSass({
      designSystem: "fluent",
      variant: "light",
    });

    expect(product.code).toContain("$allow-exclusion: true");
    expect(generic.code).not.toContain("$allow-exclusion");
    expect(none.code).not.toContain("$allow-exclusion");
  });

  it("uses a custom font family in place of the typeface", () => {
    const { code, variables } = generateThemeSass({
      designSystem: "bootstrap",
      variant: "light",
      fontFamily: "'Inter', sans-serif",
    });

    expect(code).toContain(`$font-family: "'Inter', sans-serif"`);
    expect(variables).not.toContain("$bootstrap-typeface");
  });

  it("leaves out the typography and the elevations when asked", () => {
    const { code, variables } = generateThemeSass({
      designSystem: "bootstrap",
      variant: "light",
      includeTypography: false,
      includeElevations: false,
    });

    expect(code).not.toContain("typography(");
    expect(code).toContain("$exclude: (elevations)");
    expect(variables).toEqual([
      "$light-bootstrap-palette",
      "$light-bootstrap-schema",
    ]);
  });
});

