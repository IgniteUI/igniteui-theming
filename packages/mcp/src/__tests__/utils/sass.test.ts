/**
 * Tests for Sass utility functions.
 */

import { describe, expect, it } from "vitest";
import { PALETTE_PRESETS } from "../../knowledge/palettes.js";
import {
  GLOBAL_THEME_MODULE,
  generateHeader,
  generatePaletteCode,
  generateThemeCompileSass,
  generateThemeExample,
  generateThemeSass,
  generateUseStatement,
  quoteFontFamily,
  scopeSelector,
  THEME_ENTRY_POINT,
  toVariableName,
} from "../../utils/sass.js";

describe("scopeSelector", () => {
  it("prefixes a single selector", () => {
    expect(scopeSelector(".dark", "igc-avatar")).toBe(".dark igc-avatar");
  });

  it("prefixes each selector in a list", () => {
    expect(scopeSelector(".dark", "igx-avatar, .my-avatar")).toBe(
      ".dark igx-avatar, .dark .my-avatar",
    );
  });

  it("keeps commas inside parentheses", () => {
    expect(scopeSelector(".dark", ":is(.a, .b) igc-avatar")).toBe(
      ".dark :is(.a, .b) igc-avatar",
    );
  });

  it("keeps commas inside attribute selectors", () => {
    expect(scopeSelector(".dark", 'igc-avatar[data-label="a,b"]')).toBe(
      '.dark igc-avatar[data-label="a,b"]',
    );
  });
});

describe("toVariableName", () => {
  it("converts spaces to hyphens", () => {
    expect(toVariableName("My Theme")).toBe("my-theme");
  });

  it("converts to lowercase", () => {
    expect(toVariableName("DARK_THEME")).toBe("dark-theme");
  });

  it("handles mixed case with numbers", () => {
    expect(toVariableName("Theme_v2_Test")).toBe("theme-v2-test");
  });

  it("removes invalid characters", () => {
    expect(toVariableName("Theme@#$%")).toBe("theme");
  });

  it("collapses multiple hyphens", () => {
    expect(toVariableName("my---theme")).toBe("my-theme");
  });

  it("removes leading and trailing hyphens", () => {
    expect(toVariableName("-my-theme-")).toBe("my-theme");
  });

  it("throws on empty input", () => {
    expect(() => toVariableName("")).toThrow("Variable name cannot be empty");
  });

  it("throws on whitespace-only input", () => {
    expect(() => toVariableName("   ")).toThrow(
      "Variable name cannot be empty",
    );
  });

  it("throws when result would be empty", () => {
    expect(() => toVariableName("@#$%")).toThrow(
      "Cannot create valid Sass variable name",
    );
  });
});

