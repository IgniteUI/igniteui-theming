/**
 * Exports the color demos to the Ignite UI for Web Components samples repo, which the
 * documentation embeds samples from.
 *
 *   npm run export:samples -w packages/preview [-- --out <dir>]
 *
 * The demos stay in this package: the export builds the embeds (see vite.embed.config.ts),
 * with the data compiled from the theming Sass, and writes into `<dir>`:
 *
 *   _embed/            the built embed: embed.js, its chunks, and host.ts
 *   <demo>/            one sample per demo: index.html, src/index.ts, package.json
 *
 * `<dir>` defaults to samples/themes/palettes in an igniteui-webcomponents-samples checkout
 * next to this repo, so a demo is embedded as `<Sample src="/themes/palettes/<demo>">`.
 * Every file it writes is generated: rerun the export rather than editing them there.
 */
import { cpSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { build } from "vite";
import { CATALOG, DEMO_NAMES } from "../src/embed/catalog.ts";

const PREVIEW = fileURLToPath(new URL("..", import.meta.url));
const DEFAULT_OUT = path.resolve(
  PREVIEW,
  "../../../igniteui-webcomponents-samples/samples/themes/palettes",
);

const GENERATED = "Generated by `npm run export:samples` in the igniteui-theming repo (packages/preview). Do not edit; rerun the export.";

const { values } = parseArgs({ options: { out: { type: "string" } } });
const out = path.resolve(values.out ?? DEFAULT_OUT);

/**
 * Hosts one demo in a sample page: sizes the docs iframe to the demo, and follows the light
 * or dark mode of the docs page. The samples browser records that mode on the page as
 * `data-igd-mode` when the docs send it; the demos keep their own theme, so only the mode
 * applies.
 */
const HOST = `// ${GENERATED}
import "./embed.js";

const HEIGHT_MESSAGE = "igd-sample-height";
const MODE_ATTRIBUTE = "data-igd-mode";

export const hostDemo = (name: string): void => {
  const demo = document.querySelector(\`ig-demo-\${name}\`);
  if (!demo || parent === window) return;

  // the page fills the iframe, so it is the demo, not the page, that has a height to report
  new ResizeObserver(() => {
    const height = Math.ceil(demo.getBoundingClientRect().bottom + scrollY);
    parent.postMessage({ type: HEIGHT_MESSAGE, height }, "*");
  }).observe(demo);

  const root = document.documentElement;
  const followMode = () => {
    const mode = root.getAttribute(MODE_ATTRIBUTE);
    if (mode === "light" || mode === "dark") {
      demo.setAttribute("scheme", mode);
    } else {
      demo.removeAttribute("scheme");
    }
  };
  followMode();
  new MutationObserver(followMode).observe(root, { attributeFilter: [MODE_ATTRIBUTE] });
};
`;

const sampleHtml = (name, title) => `<!DOCTYPE html>
<html>
  <head>
    <title>Palettes — ${title}</title>
    <meta charset="UTF-8" />
    <link rel="shortcut icon" href="https://dl.infragistics.com/x/img/browsers/wc.png" >
  </head>

  <body>
    <!-- ${GENERATED} -->
    <div id="root">
      <ig-demo-${name} frame></ig-demo-${name}>
    </div>
  </body>
</html>
`;

const sampleTs = (name) => `// ${GENERATED}
import { hostDemo } from "../../_embed/host";

export class Sample {
  constructor() {
    hostDemo("${name}");
  }
}

new Sample();
`;

const samplePackage = (name, title) =>
  `${JSON.stringify(
    {
      name: `wc-themes-palettes-${name}`,
      version: "1.0.0",
      description: `Ignite UI Theming color demo: ${title}. ${GENERATED}`,
      main: "src/index.ts",
      author: "Infragistics",
    },
    null,
    2,
  )}\n`;

const readme = `# Palette demos

${GENERATED}

The color demos of Ignite UI Theming, one sample per demo. \`_embed/\` holds the built
embed, with its data compiled from the theming Sass; each sample hosts one demo from it.
`;

const temp = mkdtempSync(path.join(tmpdir(), "ig-export-samples-"));

try {
  await build({
    configFile: path.join(PREVIEW, "vite.embed.config.ts"),
    logLevel: "warn",
    build: {
      outDir: temp,
      emptyOutDir: true,
      // stable names, so an export only changes the files whose content changed
      rolldownOptions: { output: { chunkFileNames: "chunks/[name].js" } },
    },
  });

  const embed = path.join(out, "_embed");
  rmSync(embed, { recursive: true, force: true });
  mkdirSync(embed, { recursive: true });
  cpSync(path.join(temp, "embed.js"), path.join(embed, "embed.js"));
  cpSync(path.join(temp, "chunks"), path.join(embed, "chunks"), { recursive: true });
  writeFileSync(path.join(embed, "host.ts"), HOST);
  writeFileSync(path.join(embed, "README.md"), readme);

  for (const name of DEMO_NAMES) {
    const { title } = CATALOG[name];
    const dir = path.join(out, name);
    mkdirSync(path.join(dir, "src"), { recursive: true });
    writeFileSync(path.join(dir, "index.html"), sampleHtml(name, title));
    writeFileSync(path.join(dir, "src", "index.ts"), sampleTs(name));
    writeFileSync(path.join(dir, "package.json"), samplePackage(name, title));
  }

  console.log(`Exported ${DEMO_NAMES.length} demos to ${out}`);
} finally {
  rmSync(temp, { recursive: true, force: true });
}
