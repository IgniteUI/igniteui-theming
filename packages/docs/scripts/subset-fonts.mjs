// Subsets the site fonts to the Latin ranges the docs use and writes WOFF2 files next to the TTF sources.
// The WOFF2 files are what `src/styles/theme.scss` references; Vite inlines them into the stylesheet
// (see `assetsInlineLimit` in astro.config), so text never waits for a font request after navigation.
import subsetFont from 'subset-font';
import fs from 'node:fs/promises';
import path from 'node:path';

const RANGES = [
  [0x0020, 0x007e], // Basic Latin
  [0x00a0, 0x00ff], // Latin-1 Supplement
  [0x0100, 0x017f], // Latin Extended-A
  [0x0180, 0x024f], // Latin Extended-B
  [0x02b0, 0x02ff], // Spacing modifiers
  [0x0300, 0x036f], // Combining diacritics
  [0x2000, 0x206f], // General punctuation (dashes, quotes, ellipsis, bullets)
  [0x20a0, 0x20cf], // Currency
  [0x2100, 0x214f], // Letterlike (™, №)
  [0x2190, 0x21ff], // Arrows
  [0x2200, 0x22ff], // Mathematical operators
  [0x2500, 0x257f], // Box drawing
  [0x25a0, 0x25ff], // Geometric shapes
  [0xfb00, 0xfb06], // Latin ligatures
  [0xfeff, 0xfeff],
  [0xfffd, 0xfffd],
];
const text = RANGES.map(([a, b]) =>
  Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i)).join(
    ''
  )
).join('');

const fonts = [
  'public/fonts/inter/Inter-Regular.ttf',
  'public/fonts/fira-code/FiraCode-Light.ttf',
  'public/fonts/fira-code/FiraCode-Regular.ttf',
  'public/fonts/fira-code/FiraCode-Medium.ttf',
];
for (const file of fonts) {
  const src = await fs.readFile(file);
  const out = await subsetFont(src, text, { targetFormat: 'woff2' });
  const dest = file.replace(/\.ttf$/, '.woff2');
  await fs.writeFile(dest, out);
  console.log(
    `${path.basename(dest)}: ${(src.length / 1024).toFixed(0)} KB -> ${(out.length / 1024).toFixed(1)} KB`
  );
}

// Inter is the body font on every page: embed it in the stylesheet as a data URI so no request (dev or prod)
// can delay the first paint of text. Fira Code stays a preloaded file (code blocks only).
const inter = await fs.readFile('public/fonts/inter/Inter-Regular.woff2');
await fs.writeFile(
  'src/styles/_font-inter.scss',
  `// GENERATED by scripts/subset-fonts.mjs (npm run fonts) — do not edit by hand.\n// The Latin subset of Inter Regular as a data URI; theme.scss uses it in its @font-face.\n$inter-regular-woff2: 'data:font/woff2;base64,${inter.toString('base64')}';\n`
);
console.log(
  `_font-inter.scss: ${(inter.length / 1024).toFixed(1)} KB embedded`
);
