import type { Locale, Version } from './config';

/** Frontmatter fields in use across the 136 docs (see `src/content.config.ts` for the schema). */
export interface DocFrontmatter {
  title?: string;
  description?: string;
  sidebar_position?: number;
  hide_title?: boolean;
  /** `null` disables the next link; a doc id overrides it. */
  pagination_next?: string | null;
  /** Present in 4 files but not read by the theme; kept so the strict schema accepts it. */
  pagination_next_label?: string;
  id?: string;
  slug?: string;
  sidebar_label?: string;
  pagination_label?: string;
  pagination_prev?: string | null;
}

/** A doc file as read from disk or a content collection, before the id/slug rules are applied. */
export interface DocSource {
  /** Path relative to the content root, e.g. `core-concepts/colors/overview.mdx`. */
  relativePath: string;
  frontmatter: DocFrontmatter;
  /** Markdown body without frontmatter. */
  body: string;
}

/** Doc metadata. */
export interface DocMeta {
  locale: Locale;
  version: Version;
  /** `core-concepts/colors/overview` */
  id: string;
  /** `/core-concepts/colors/overview` or `/utility-concepts/bem/` for a category index */
  slug: string;
  /** `/theming-docs/docs/core-concepts/colors/overview` */
  permalink: string;
  title: string;
  description: string;
  /** Title parsed from the first `# heading`, if any. */
  contentTitle?: string;
  sidebarPosition?: number;
  /** Raw directory relative to the content root, `.` for the root. */
  sourceDirName: string;
  /** `overview.mdx` */
  sourceFileName: string;
  relativePath: string;
  frontmatter: DocFrontmatter;
}

export interface CategoryMetadata {
  label?: string;
  position?: number;
  description?: string;
  collapsed?: boolean;
  collapsible?: boolean;
  className?: string;
  link?:
    | null
    | { type: 'doc'; id: string }
    | {
        type: 'generated-index';
        title?: string;
        description?: string;
        slug?: string;
      };
  customProps?: Record<string, unknown>;
}

/** Sidebar definition items (what `sidebars.ts` / the versioned JSON express). */
export type SidebarDefItem =
  | string
  | { type: 'doc'; id: string; label?: string }
  | { type: 'html'; value: string; defaultStyle?: boolean; className?: string }
  | { type: 'autogenerated'; dirName: string }
  | {
      type: 'category';
      label: string;
      link?: { type: 'doc'; id: string };
      items: SidebarDefItem[];
      collapsed?: boolean;
      collapsible?: boolean;
      customProps?: Record<string, unknown>;
      description?: string;
      className?: string;
    };

/** Normalised sidebar: categories keep their link doc id. */
export type SidebarNode =
  | { type: 'doc'; id: string; label?: string }
  | { type: 'html'; value: string; defaultStyle: boolean; className?: string }
  | {
      type: 'category';
      label: string;
      collapsible: boolean;
      collapsed: boolean;
      link?: { type: 'doc'; id: string };
      items: SidebarNode[];
      customProps?: Record<string, unknown>;
      description?: string;
      className?: string;
    };

/** Sidebar as rendered (snapshot-tested). */
export type SidebarItem =
  | {
      type: 'link';
      href: string;
      label: string;
      docId: string;
      unlisted: false;
    }
  | { type: 'html'; value: string; defaultStyle: boolean; className?: string }
  | {
      type: 'category';
      label: string;
      collapsible: boolean;
      collapsed: boolean;
      href?: string;
      items: SidebarItem[];
      customProps?: Record<string, unknown>;
      description?: string;
      className?: string;
    };

export interface NavigationLink {
  title: string;
  permalink: string;
}

export interface Breadcrumb {
  label: string;
  /** Present for ancestors that link somewhere; the last crumb never links. */
  href?: string;
}
