// Sidebar definitions: `current` is defined here; `24.0.0` comes from the versioned JSON.
import type { Locale, Version } from './config';
import type { SidebarDefItem } from './types';
import v24Sidebars from './sidebars/version-24.0.0.json';

const sectionTitle = (
  locale: Locale,
  en: string,
  ja: string
): SidebarDefItem => ({
  type: 'html',
  value: `<span>${locale === 'ja' ? ja : en}</span>`,
  defaultStyle: true,
  className: 'it-sidebar-title',
});

const category = (
  label: string,
  linkId: string,
  dirName: string
): SidebarDefItem => ({
  type: 'category',
  label,
  link: { type: 'doc', id: linkId },
  items: [{ type: 'autogenerated', dirName }],
});

/** Sidebar of the current version; section titles are localised at definition time. */
export function currentSidebarDef(locale: Locale): SidebarDefItem[] {
  return [
    sectionTitle(locale, 'Getting Started', 'はじめに'),
    'getting-started/overview',
    'getting-started/quick-start',
    'getting-started/installation',
    sectionTitle(locale, 'Core concepts', 'コアコンセプト'),
    category('Colors', 'core-concepts/colors/overview', 'core-concepts/colors'),
    category(
      'Elevations',
      'core-concepts/elevations/overview',
      'core-concepts/elevations'
    ),
    category(
      'Roundness',
      'core-concepts/roundness/overview',
      'core-concepts/roundness'
    ),
    category(
      'Sizing & Spacing',
      'core-concepts/sizing-spacing/sizing-overview',
      'core-concepts/sizing-spacing'
    ),
    category(
      'Typography',
      'core-concepts/typography/overview',
      'core-concepts/typography'
    ),
    sectionTitle(locale, 'Utility concepts', 'ユーティリティコンセプト'),
    category(
      'Converting functions',
      'utility-concepts/converting_functions/converting-functions',
      'utility-concepts/converting_functions'
    ),
    category(
      'Animation',
      'utility-concepts/animations/overview',
      'utility-concepts/animations'
    ),
    category('BEM', 'utility-concepts/bem/bem', 'utility-concepts/bem'),
    sectionTitle(locale, 'Modularity', 'モジュール性'),
    'modularity/intro',
    sectionTitle(locale, 'Styling with AI', 'AIによるスタイリング'),
    'styling-with-ai/overview',
    sectionTitle(locale, 'Showcase', 'ショーケース'),
    'showcase/intro',
  ];
}

export function sidebarDef(locale: Locale, version: Version): SidebarDefItem[] {
  if (version === 'current') return currentSidebarDef(locale);
  return (v24Sidebars as { DocsSidebar: SidebarDefItem[] }).DocsSidebar;
}
