// build the sidebar tree from a definition + docs.
import { isCategoryIndex, parseNumberPrefix } from './ids';
import type {
  CategoryMetadata,
  DocMeta,
  SidebarDefItem,
  SidebarItem,
  SidebarNode,
} from './types';

export interface SidebarContext {
  docs: DocMeta[];
  /** `_category_.json` per raw directory, relative to the content root. */
  categories: Record<string, CategoryMetadata>;
  /** `sidebar.DocsSidebar.category.<label>` translations (`{ message }`), if any. */
  translations?: Record<string, { message: string }>;
  sidebarName?: string;
}

const SIDEBAR_NAME = 'DocsSidebar';

export function docsById(docs: DocMeta[]): Map<string, DocMeta> {
  return new Map(docs.map((d) => [d.id, d]));
}

/** Normalised sidebar: shorthand expanded, autogenerated dirs materialised, categories keep link ids. */
export function normalizeSidebar(
  def: SidebarDefItem[],
  ctx: SidebarContext
): SidebarNode[] {
  const byId = docsById(ctx.docs);
  const sidebarName = ctx.sidebarName ?? SIDEBAR_NAME;
  const translateCategory = (label: string) =>
    ctx.translations?.[`sidebar.${sidebarName}.category.${label}`]?.message ??
    label;
  const translateDoc = (label: string) =>
    ctx.translations?.[`sidebar.${sidebarName}.doc.${label}`]?.message ?? label;
  const getDoc = (id: string) => {
    const doc = byId.get(id);
    if (!doc) throw new Error(`Sidebar references unknown doc id "${id}"`);
    return doc;
  };

  const expand = (items: SidebarDefItem[]): SidebarNode[] =>
    items.flatMap((item): SidebarNode[] => {
      if (typeof item === 'string') {
        getDoc(item);
        return [{ type: 'doc', id: item }];
      }
      switch (item.type) {
        case 'doc':
          getDoc(item.id);
          return [
            {
              type: 'doc',
              id: item.id,
              ...(item.label !== undefined && {
                label: translateDoc(item.label),
              }),
            },
          ];
        case 'html':
          return [
            {
              type: 'html',
              value: item.value,
              defaultStyle: item.defaultStyle ?? false,
              ...(item.className !== undefined && {
                className: item.className,
              }),
            },
          ];
        case 'autogenerated':
          return generateAutogenerated(item.dirName);
        case 'category':
          return [
            {
              type: 'category',
              label: translateCategory(item.label),
              collapsible: item.collapsible ?? true,
              collapsed: item.collapsed ?? true,
              ...(item.link && { link: item.link }),
              items: expand(item.items),
              ...(item.customProps !== undefined && {
                customProps: item.customProps,
              }),
              ...(item.description !== undefined && {
                description: item.description,
              }),
              ...(item.className !== undefined && {
                className: item.className,
              }),
            },
          ];
      }
    });

  // Autogenerated categories: materialise a directory tree into sidebar nodes.
  type Sortable = SidebarNode & { position?: number; source: string };
  function generateAutogenerated(autogenDir: string): SidebarNode[] {
    const docsInDir = ctx.docs.filter(
      (d) =>
        d.sourceDirName === autogenDir ||
        d.sourceDirName.startsWith(`${autogenDir}/`)
    );
    if (docsInDir.length === 0) {
      throw new Error(
        `No docs found for autogenerated sidebar dir "${autogenDir}"`
      );
    }
    // Step 1-2: the fs model — nested folders keyed by name, doc ids as leaves.
    type Tree = { [key: string]: Tree | string };
    const treeRoot: Tree = {};
    for (const doc of docsInDir) {
      const relDir =
        doc.sourceDirName === autogenDir
          ? ''
          : doc.sourceDirName.slice(autogenDir.length + 1);
      let node = treeRoot;
      for (const segment of relDir ? relDir.split('/') : []) {
        node[segment] ??= {};
        node = node[segment] as Tree;
      }
      node[doc.sourceFileName] = doc.id;
    }

    const localId = (id: string) => id.slice(id.lastIndexOf('/') + 1);

    const createDocItem = (id: string, fileName: string): Sortable => {
      const doc = getDoc(id);
      return {
        type: 'doc',
        id,
        position: doc.sidebarPosition,
        source: fileName,
        ...(doc.frontmatter.sidebar_label !== undefined && {
          label: doc.frontmatter.sidebar_label,
        }),
      };
    };

    const createCategoryItem = (
      dir: Tree,
      fullPath: string,
      folderName: string
    ): Sortable => {
      const categoryMetadata =
        ctx.categories[`${autogenDir}/${fullPath}`.replace(/^\.\//, '')];
      const allItems = Object.entries(dir).map(([key, content]) =>
        dirToItem(content, key, `${fullPath}/${key}`)
      );
      const findDocByLocalId = (id: string) =>
        allItems.find(
          (item) => item.type === 'doc' && localId(item.id) === id
        ) as (Sortable & { type: 'doc' }) | undefined;
      const findConventionalCategoryDocLink = () =>
        allItems.find((item) => {
          if (item.type !== 'doc') return false;
          const doc = getDoc(item.id);
          return isCategoryIndex(
            doc.sourceFileName.replace(/\.mdx?$/, ''),
            doc.sourceDirName
          );
        }) as (Sortable & { type: 'doc' }) | undefined;

      const getCategoryLinkedDocMetadata = () => {
        const link = categoryMetadata?.link;
        if (link !== undefined && link?.type !== 'doc') return undefined;
        const id = link
          ? (findDocByLocalId(link.id)?.id ?? getDoc(link.id).id)
          : findConventionalCategoryDocLink()?.id;
        if (!id) return undefined;
        const doc = getDoc(id);
        return {
          id,
          position: doc.sidebarPosition,
          label: doc.frontmatter.sidebar_label ?? doc.title,
        };
      };

      const categoryLinkedDoc = getCategoryLinkedDocMetadata();
      const link = categoryLinkedDoc
        ? { type: 'doc' as const, id: categoryLinkedDoc.id }
        : categoryMetadata?.link;
      const items = allItems.filter(
        (item) => !(item.type === 'doc' && item.id === categoryLinkedDoc?.id)
      );
      const { filename, numberPrefix } = parseNumberPrefix(folderName);
      const rawLabel =
        categoryMetadata?.label ?? categoryLinkedDoc?.label ?? filename;
      return {
        type: 'category',
        label: translateCategory(rawLabel),
        collapsible: categoryMetadata?.collapsible ?? true,
        collapsed: categoryMetadata?.collapsed ?? true,
        position:
          categoryMetadata?.position ??
          categoryLinkedDoc?.position ??
          numberPrefix,
        source: folderName,
        ...(categoryMetadata?.customProps !== undefined && {
          customProps: categoryMetadata.customProps,
        }),
        ...(categoryMetadata?.className !== undefined && {
          className: categoryMetadata.className,
        }),
        items: sortItems(items),
        ...(categoryMetadata?.description && {
          description: categoryMetadata.description,
        }),
        ...(link && link.type === 'doc' && { link }),
      };
    };

    const dirToItem = (
      dir: Tree | string,
      itemKey: string,
      fullPath: string
    ): Sortable =>
      typeof dir === 'object'
        ? createCategoryItem(dir, fullPath, itemKey)
        : createDocItem(dir, itemKey);

    // Step 4: sort by [position, source] (lodash sortBy: undefined positions last, stable), then drop the sort keys.
    function sortItems(items: Sortable[]): SidebarNode[] {
      const sorted = [...items].sort((a, b) => {
        const pa = a.position ?? Number.POSITIVE_INFINITY;
        const pb = b.position ?? Number.POSITIVE_INFINITY;
        if (pa !== pb) return pa < pb ? -1 : 1;
        return a.source < b.source ? -1 : a.source > b.source ? 1 : 0;
      });
      return sorted.map(
        ({ position: _p, source: _s, ...item }) => item as SidebarNode
      );
    }

    const rootItems = Object.entries(treeRoot).map(([key, content]) =>
      dirToItem(content, key, key)
    );
    return sortItems(rootItems);
  }

  return expand(def);
}

/** The rendered sidebar item shape. */
export function toSidebarItems(
  nodes: SidebarNode[],
  docs: DocMeta[]
): SidebarItem[] {
  const byId = docsById(docs);
  const getDoc = (id: string) => {
    const doc = byId.get(id);
    if (!doc) throw new Error(`Unknown doc id "${id}"`);
    return doc;
  };
  const convert = (node: SidebarNode): SidebarItem => {
    switch (node.type) {
      case 'doc': {
        const doc = getDoc(node.id);
        return {
          type: 'link',
          href: doc.permalink,
          label: doc.frontmatter.sidebar_label ?? node.label ?? doc.title,
          docId: doc.id,
          unlisted: false,
        };
      }
      case 'html':
        return {
          type: 'html',
          value: node.value,
          defaultStyle: node.defaultStyle,
          ...(node.className !== undefined && { className: node.className }),
        };
      case 'category': {
        const href = node.link ? getDoc(node.link.id).permalink : undefined;
        return {
          type: 'category',
          label: node.label,
          collapsible: node.collapsible,
          collapsed: node.collapsed,
          items: node.items.map(convert),
          ...(href && { href }),
          ...(node.customProps !== undefined && {
            customProps: node.customProps,
          }),
          ...(node.description !== undefined && {
            description: node.description,
          }),
          ...(node.className !== undefined && { className: node.className }),
        };
      }
    }
  };
  return nodes.map(convert);
}
